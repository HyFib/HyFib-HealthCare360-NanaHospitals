using System.Globalization;
using System.Text;
using ClosedXML.Excel;
using HyFib.HealthCare360.Modules.Analytics.Domain;
using HyFib.HealthCare360.Modules.Analytics.Features.Reports;

namespace HyFib.HealthCare360.Modules.Analytics.Reports.Export;

/// <summary>A report ready to write: the whole sorted result plus everything the header and footer need.</summary>
public sealed record ReportDocument(
    string ReportId,
    string FileStamp,
    string Organisation,
    string Title,
    string Definition,
    IReadOnlyList<ReportFilterDto> Filters,
    string GeneratedBy,
    DateTimeOffset GeneratedAt,
    string DataSource,
    IReadOnlyList<ReportColumn> Columns,
    IReadOnlyList<object?[]> Rows,
    object?[]? Totals,
    IReadOnlyList<ReportFigure> Summary,
    IReadOnlyList<string> Notes,
    bool ContainsPatientIdentifiers);

public sealed record ReportFile(string FileName, string ContentType, byte[] Content);

/// <summary>
/// Excel (ClosedXML) and CSV exports (MIS-03). Every file carries a header — hospital, report, inputs, who generated it
/// and when (IST) — and ends with "Confidential"; the Excel sheet also prints "Confidential" in the page footer. Text
/// cells in CSV are neutralised against formula injection (a leading =, +, -, @, tab or CR is prefixed with an
/// apostrophe); Excel text is stored as text and never evaluated.
/// </summary>
public static class ReportExporter
{
    public const string Confidential = "Confidential";
    public const string XlsxContentType = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";
    public const string CsvContentType = "text/csv";

    private const int AutoFitRows = 400;
    private const double MaxColumnWidth = 60;

    public static ReportFile Export(ReportDocument document, ExportFormat format)
    {
        var stem = FileStem(document);
        return format == ExportFormat.Csv
            ? new ReportFile(stem + ".csv", CsvContentType, Csv(document))
            : new ReportFile(stem + ".xlsx", XlsxContentType, Xlsx(document));
    }

    /// <summary>"revenue-by-department_20260901-20260926" (letters, digits, dashes and underscores only).</summary>
    public static string FileStem(ReportDocument document)
    {
        var raw = $"{document.ReportId}_{document.FileStamp}";
        return new string(raw.Select(c => char.IsAsciiLetterOrDigit(c) || c is '-' or '_' ? c : '-').ToArray());
    }

    public static string ConfidentialNotice(ReportDocument document) =>
        $"{Confidential} — generated from HyFib HealthCare360 for internal use of {document.Organisation}."
        + (document.ContainsPatientIdentifiers ? " Contains patient-identifiable information: handle under the hospital's privacy policy." : " Do not share outside the hospital.");

    // ------------------------------------------------------------------ Excel

    private static byte[] Xlsx(ReportDocument document)
    {
        using var workbook = new XLWorkbook();
        workbook.Properties.Title = document.Title;
        workbook.Properties.Author = document.GeneratedBy;
        workbook.Properties.Company = document.Organisation;
        workbook.Properties.Subject = "HC360 MIS report";

        var sheet = workbook.Worksheets.Add(SheetName(document.Title));
        var columns = Math.Max(document.Columns.Count, 2);
        var row = 1;

        Heading(sheet.Cell(row++, 1), document.Organisation, 14);
        Heading(sheet.Cell(row++, 1), document.Title, 12);
        foreach (var filter in document.Filters)
        {
            Label(sheet.Cell(row, 1), filter.Label);
            sheet.Cell(row++, 2).Value = filter.Value;
        }

        Label(sheet.Cell(row, 1), "Generated by");
        sheet.Cell(row++, 2).Value = $"{document.GeneratedBy} on {AnalyticsClock.FormatDateTime(document.GeneratedAt)}";
        Label(sheet.Cell(row, 1), "Data source");
        sheet.Cell(row++, 2).Value = document.DataSource;

        if (document.Summary.Count > 0)
        {
            row++;
            Heading(sheet.Cell(row++, 1), "Summary", 11);
            foreach (var figure in document.Summary)
            {
                Label(sheet.Cell(row, 1), figure.Label);
                Write(sheet.Cell(row++, 2), figure.Value, figure.Type);
            }
        }

        row++;
        var headerRow = row;
        for (var c = 0; c < document.Columns.Count; c++)
        {
            var cell = sheet.Cell(headerRow, c + 1);
            cell.Value = document.Columns[c].Label;
            cell.Style.Font.Bold = true;
            cell.Style.Fill.BackgroundColor = XLColor.FromHtml("#E8EEF7");
            cell.Style.Border.BottomBorder = XLBorderStyleValues.Thin;
            cell.Style.Alignment.WrapText = true;
        }

        foreach (var values in document.Rows)
        {
            row++;
            for (var c = 0; c < document.Columns.Count; c++)
            {
                Write(sheet.Cell(row, c + 1), values[c], document.Columns[c].Type);
            }
        }

        var lastDataRow = row;
        if (document.Rows.Count > 0)
        {
            sheet.Range(headerRow, 1, lastDataRow, document.Columns.Count).SetAutoFilter();
        }

        if (document.Totals is { } totals)
        {
            row++;
            for (var c = 0; c < document.Columns.Count; c++)
            {
                var cell = sheet.Cell(row, c + 1);
                Write(cell, totals[c], c == 0 ? ReportValueType.Text : document.Columns[c].Type);
                cell.Style.Font.Bold = true;
                cell.Style.Border.TopBorder = XLBorderStyleValues.Thin;
            }
        }

        if (document.Rows.Count == 0)
        {
            sheet.Cell(++row, 1).Value = "No data for these inputs.";
        }

        row++;
        foreach (var note in document.Notes)
        {
            sheet.Cell(++row, 1).Value = note;
        }

        Label(sheet.Cell(++row, 1), "Definition");
        sheet.Cell(row, 2).Value = document.Definition;
        var footer = sheet.Cell(row + 2, 1);
        footer.Value = ConfidentialNotice(document);
        footer.Style.Font.Bold = true;
        footer.Style.Font.FontColor = XLColor.FromHtml("#A4262C");

        sheet.SheetView.FreezeRows(headerRow);
        sheet.Columns(1, columns).AdjustToContents(headerRow, Math.Min(lastDataRow + 1, headerRow + AutoFitRows));
        foreach (var column in sheet.Columns(1, columns))
        {
            column.Width = Math.Clamp(column.Width, 8, MaxColumnWidth);
        }

        sheet.PageSetup.PageOrientation = XLPageOrientation.Landscape;
        sheet.PageSetup.FitToPages(1, 0);
        sheet.PageSetup.SetRowsToRepeatAtTop(headerRow, headerRow);
        sheet.PageSetup.Header.Center.AddText($"{document.Organisation} — {document.Title}", XLHFOccurrence.AllPages);
        sheet.PageSetup.Footer.Center.AddText(Confidential, XLHFOccurrence.AllPages);

        using var stream = new MemoryStream();
        workbook.SaveAs(stream);
        return stream.ToArray();
    }

    private static void Heading(IXLCell cell, string text, double size)
    {
        cell.Value = text;
        cell.Style.Font.Bold = true;
        cell.Style.Font.FontSize = size;
    }

    private static void Label(IXLCell cell, string text)
    {
        cell.Value = text;
        cell.Style.Font.Bold = true;
    }

    private static void Write(IXLCell cell, object? value, ReportValueType type)
    {
        switch (value)
        {
            case null:
                return;
            case string text:
                cell.Value = text;
                return;
            case bool flag:
                cell.Value = flag ? "Yes" : "No";
                return;
            case DateOnly date:
                cell.Value = date.ToDateTime(TimeOnly.MinValue);
                cell.Style.NumberFormat.Format = type == ReportValueType.Month ? "mmm yyyy" : "dd-mmm-yyyy";
                return;
            case DateTimeOffset instant:
                cell.Value = AnalyticsClock.ToLocal(instant).DateTime;
                cell.Style.NumberFormat.Format = "dd-mmm-yyyy hh:mm AM/PM";
                return;
        }

        if (ReportShaping.ToDecimal(value) is { } number)
        {
            cell.Value = (double)number;
            cell.Style.NumberFormat.Format = NumberFormat(type);
            return;
        }

        cell.Value = Convert.ToString(value, CultureInfo.InvariantCulture) ?? string.Empty;
    }

    /// <summary>Excel number formats; grouping follows the workstation's regional setting (lakh grouping on en-IN).</summary>
    private static string NumberFormat(ReportValueType type) => type switch
    {
        ReportValueType.Integer => "#,##0",
        ReportValueType.Money => "\"₹\" #,##0.00;[Red]-\"₹\" #,##0.00",
        ReportValueType.Percent => "0.0\"%\"",
        _ => "#,##0.0",
    };

    private static string SheetName(string title)
    {
        var invalid = new[] { ':', '\\', '/', '?', '*', '[', ']' };
        var clean = new string(title.Where(c => !invalid.Contains(c)).ToArray()).Trim();
        return clean.Length switch
        {
            0 => "Report",
            > 31 => clean[..31],
            _ => clean,
        };
    }

    // ------------------------------------------------------------------ CSV

    private static byte[] Csv(ReportDocument document)
    {
        var csv = new StringBuilder();
        Line(csv, document.Organisation);
        Line(csv, document.Title);
        foreach (var filter in document.Filters)
        {
            Line(csv, filter.Label, filter.Value);
        }

        Line(csv, "Generated by", $"{document.GeneratedBy} on {AnalyticsClock.FormatDateTime(document.GeneratedAt)}");
        Line(csv, "Data source", document.DataSource);
        csv.Append("\r\n");

        Line(csv, [.. document.Columns.Select(c => c.Label)]);
        foreach (var values in document.Rows)
        {
            Line(csv, [.. document.Columns.Select((c, i) => Format(values[i], c.Type))]);
        }

        if (document.Totals is { } totals)
        {
            Line(csv, [.. document.Columns.Select((c, i) => Format(totals[i], i == 0 ? ReportValueType.Text : c.Type))]);
        }

        csv.Append("\r\n");
        foreach (var note in document.Notes)
        {
            Line(csv, note);
        }

        Line(csv, "Definition", document.Definition);
        Line(csv, ConfidentialNotice(document));

        // UTF-8 with a byte-order mark so Excel shows ₹ and Indian-language names correctly.
        return [.. Encoding.UTF8.GetPreamble(), .. Encoding.UTF8.GetBytes(csv.ToString())];
    }

    private static void Line(StringBuilder csv, params string?[] fields)
    {
        csv.AppendJoin(',', fields.Select(Escape));
        csv.Append("\r\n");
    }

    private static string? Format(object? value, ReportValueType type) => value switch
    {
        null => null,
        string text => text,
        bool flag => flag ? "Yes" : "No",
        DateOnly date => type == ReportValueType.Month ? date.ToString("yyyy-MM", CultureInfo.InvariantCulture) : date.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
        DateTimeOffset instant => AnalyticsClock.ToLocal(instant).ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture),
        _ when ReportShaping.ToDecimal(value) is { } number => type == ReportValueType.Money
            ? number.ToString("0.00", CultureInfo.InvariantCulture)
            : number.ToString("0.##", CultureInfo.InvariantCulture),
        _ => Convert.ToString(value, CultureInfo.InvariantCulture),
    };

    /// <summary>RFC 4180 quoting plus formula-injection protection for text.</summary>
    internal static string Escape(string? field)
    {
        if (string.IsNullOrEmpty(field))
        {
            return string.Empty;
        }

        var safe = field[0] is '=' or '+' or '-' or '@' or '\t' or '\r' && !IsNumber(field) ? "'" + field : field;
        return safe.IndexOfAny([',', '"', '\n', '\r']) >= 0 ? "\"" + safe.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"" : safe;
    }

    private static bool IsNumber(string field) => decimal.TryParse(field, NumberStyles.Number, CultureInfo.InvariantCulture, out _);
}
