namespace HyFib.HealthCare360.Modules.Privacy.Domain;

/// <summary>
/// A table that holds a patient's personal data. <paramref name="Label"/> is what the patient sees. Tables that only
/// support another one (a lab result under its lab order) are listed but not counted, so the summary stays readable;
/// a counted table must have an index on its patient column (checked by the architecture tests).
/// </summary>
public sealed record PersonalDataSource(string Table, string Label, bool Counted = true, string Column = "patient_id");

/// <summary>A group of personal data as the patient would describe it, with why it is held and on what basis.</summary>
public sealed record PersonalDataCategory(
    string Key,
    string Title,
    string Description,
    string Purpose,
    string Basis,
    PersonalDataRetention Retention,
    IReadOnlyList<PersonalDataSource> Sources);

/// <summary>Which retention period applies to a category, for the summary's "how long we keep it".</summary>
public enum PersonalDataRetention
{
    /// <summary>The medical records periods (out-patient, in-patient, medico-legal).</summary>
    MedicalRecords = 0,
    Finance,
    MessageLog,
    Audit,

    /// <summary>Kept while the portal account is open.</summary>
    WhileInUse,

    /// <summary>Kept as long as the records it relates to.</summary>
    WithRecords,
}

