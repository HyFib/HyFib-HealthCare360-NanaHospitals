internal sealed class RecordWasteBagRequestValidator : AbstractValidator<RecordWasteBagRequest>
{
    public RecordWasteBagRequestValidator()
    {
        RuleFor(x => x.Category).IsInEnum();
        RuleFor(x => x.Source).MaximumLength(120);
        RuleFor(x => x).Must(x => x.DepartmentId is not null || !string.IsNullOrWhiteSpace(x.Source))
            .WithName("source").WithMessage("Say where the waste came from: the department or the place.");
        RuleFor(x => x.WeightKg).GreaterThan(0).LessThanOrEqualTo(WasteBag.MaxWeightKg);
    }
}

internal sealed class VoidWasteBagRequestValidator : AbstractValidator<VoidWasteBagRequest>
{
    public VoidWasteBagRequestValidator()
    {
        RuleFor(x => x.Reason).NotEmpty().MaximumLength(300);
    }
}

internal sealed class HandOverWasteRequestValidator : AbstractValidator<HandOverWasteRequest>
{
    public HandOverWasteRequestValidator()
    {
        RuleFor(x => x.Bags).NotEmpty().Must(b => b is null || b.Count <= 500).WithMessage("Hand over at most 500 bags at a time.");
        RuleForEach(x => x.Bags).ChildRules(bag =>
        {
            bag.RuleFor(b => b.Barcode).NotEmpty().MaximumLength(32);
            bag.RuleFor(b => b.WeightKg).GreaterThan(0).LessThanOrEqualTo(WasteBag.MaxWeightKg).WithMessage("Weigh each bag at the handover.");
        });
        RuleFor(x => x.Cbwtf).MaximumLength(200);
        RuleFor(x => x.VehicleNumber).NotEmpty().MaximumLength(20);
        RuleFor(x => x.ReceivedBy).NotEmpty().MaximumLength(120);
        RuleFor(x => x.ReceiptNumber).MaximumLength(40);
    }
}

internal sealed class RecordWasteAccidentRequestValidator : AbstractValidator<RecordWasteAccidentRequest>
{
    public RecordWasteAccidentRequestValidator(TimeProvider time)
    {
        RuleFor(x => x.OccurredAt).Must(at => at <= time.GetUtcNow().AddMinutes(5)).WithMessage("The accident cannot be in the future.");
        RuleFor(x => x.Kind).IsInEnum();
        RuleFor(x => x.Place).NotEmpty().SafeText(200);
        RuleFor(x => x.Sequence).NotEmpty().SafeText(2000);
        RuleFor(x => x.Category).IsInEnum();
        RuleFor(x => x.WasteInvolved).NotEmpty().SafeText(500);
        RuleFor(x => x.PersonsAffected).InclusiveBetween(0, 1000);
        RuleFor(x => x.Effects).NotEmpty().SafeText(2000);
        RuleFor(x => x.EmergencyMeasures).NotEmpty().SafeText(2000);
        RuleFor(x => x.StepsToAlleviate).SafeText(2000);
        RuleFor(x => x.StepsToPrevent).SafeText(2000);
        RuleFor(x => x.AuthorityInformedAt).Must(at => at is null || at <= time.GetUtcNow().AddMinutes(5)).WithMessage("The authority cannot be told in the future.");
        RuleFor(x => x.Designation).SafeText(120);
    }
}
