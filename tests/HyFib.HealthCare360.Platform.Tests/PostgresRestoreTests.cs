namespace HyFib.HealthCare360.Platform.Tests;

/// <summary>
/// The backups' PostgreSQL steps against a real server (DED-16), with the accounts of a Server Node: a database owned by
/// an owner account, read and written by the account the server works as (hc360-database-roles.sql), and the account test
/// restores sign in as, which may create databases and nothing else. The key tables' rows are counted in the snapshot
/// pg_dump dumps, so rows saved while it runs are in neither; the scratch database is made, filled by pg_restore, counted
/// and dropped by that account, and one an earlier test left is dropped first. Runs where HC360_TEST_DATABASE names a
/// PostgreSQL server the tests may create databases and accounts on (CI's, signed in as its superuser); skipped elsewhere.
/// </summary>
public sealed class PostgresRestoreTests : IAsyncLifetime
{
    private readonly string _suffix = Guid.NewGuid().ToString("N")[..10];
    private string? _server;

    private string Owner => "hc360_pt_owner_" + _suffix;
    private string App => "hc360_pt_app_" + _suffix;
    private string Restorer => "hc360_pt_restore_" + _suffix;
    private string Database => "hc360_pt_" + _suffix;

    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    public async ValueTask InitializeAsync()
    {
        _server = Environment.GetEnvironmentVariable("HC360_TEST_DATABASE");
        if (string.IsNullOrEmpty(_server))
        {
            return;
        }

        await ExecuteAsync(_server,
            $"CREATE ROLE {Owner} LOGIN PASSWORD 'owner-{_suffix}'; CREATE ROLE {App} LOGIN PASSWORD 'app-{_suffix}'; " +
            $"CREATE ROLE {Restorer} LOGIN CREATEDB PASSWORD 'restore-{_suffix}'; GRANT pg_read_all_settings TO {Restorer}");
        await ExecuteAsync(_server, $"CREATE DATABASE {Database} OWNER {Owner} ENCODING 'UTF8'");

        // As Install-HC360Server.ps1 sets the database up: the accounts' rights first, then everything made as the owner.
        var hospital = On(_server, Database);
        await ExecuteAsync(hospital,
            $"REVOKE ALL ON SCHEMA public FROM PUBLIC; SELECT set_config('hc360.owner_role', '{Owner}', false), set_config('hc360.app_role', '{App}', false);\n" +
            await File.ReadAllTextAsync(RolesSql(), Ct));
        await ExecuteAsync(hospital, $"""
            SET ROLE {Owner};
            CREATE EXTENSION IF NOT EXISTS pg_trgm;
            CREATE SCHEMA patients; CREATE SCHEMA audit; CREATE SCHEMA platform; CREATE SCHEMA billing;
            CREATE TABLE patients.patients (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
            CREATE INDEX ix_patients_name ON patients.patients USING gin (name gin_trgm_ops);
            CREATE TABLE billing.bills (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, patient_id bigint REFERENCES patients.patients (id));
            CREATE TABLE audit.audit_events (id bigint NOT NULL, occurred_at timestamptz NOT NULL, summary text) PARTITION BY RANGE (occurred_at);
            CREATE TABLE audit.audit_events_2026_11 PARTITION OF audit.audit_events FOR VALUES FROM ('2026-11-01') TO ('2026-12-01');
            CREATE FUNCTION audit.refuse() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'the audit trail is append-only'; END $$;
            CREATE TRIGGER audit_events_append_only BEFORE DELETE ON audit.audit_events FOR EACH ROW EXECUTE FUNCTION audit.refuse();
            CREATE TABLE platform.server_nodes (node text PRIMARY KEY, report jsonb);
            RESET ROLE;
            """);
        await ExecuteAsync(As(hospital, App), """
            INSERT INTO patients.patients (name) SELECT 'patient ' || g FROM generate_series(1, 500) g;
            INSERT INTO billing.bills (patient_id) SELECT id FROM patients.patients;
            INSERT INTO audit.audit_events SELECT g, timestamptz '2026-11-14' + g * interval '1 second', 'event' FROM generate_series(1, 2000) g;
            INSERT INTO platform.server_nodes VALUES ('IT-OLD', '{}');
            """);
    }

    public async ValueTask DisposeAsync()
    {
        if (string.IsNullOrEmpty(_server))
        {
            return;
        }

        NpgsqlConnection.ClearAllPools();
        await using var connection = new NpgsqlConnection(_server);
        await connection.OpenAsync();
        var scratch = new List<string>();
        await using (var find = new NpgsqlCommand($"SELECT datname FROM pg_database WHERE pg_get_userbyid(datdba) = '{Restorer}'", connection))
        await using (var reader = await find.ExecuteReaderAsync())
        {
            while (await reader.ReadAsync())
            {
                scratch.Add(reader.GetString(0));
            }
        }

        foreach (var name in scratch.Append(Database))
        {
            await using var drop = new NpgsqlCommand($"DROP DATABASE IF EXISTS \"{name}\" WITH (FORCE)", connection);
            await drop.ExecuteNonQueryAsync();
        }

        await using var roles = new NpgsqlCommand($"DROP ROLE IF EXISTS {Restorer}; DROP ROLE IF EXISTS {App}; DROP ROLE IF EXISTS {Owner}", connection);
        await roles.ExecuteNonQueryAsync();
    }

    /// <summary>
    /// The backup counts the key tables in pg_dump's own snapshot, as the server's account, while rows are saved all the
    /// time; restored into a scratch database by the test-restore account, the dump holds exactly the rows counted, with
    /// none of the servers' heartbeats, and the scratch database is dropped.
    /// </summary>
    [Fact]
    public async Task A_dump_restores_into_a_scratch_database_with_exactly_the_rows_counted_in_its_snapshot()
    {
        var server = Server();
        var hospital = On(server, Database);
        var tools = Tools(As(hospital, App), As(On(server, "postgres"), Restorer), await DataDirectoryIsHereAsync(server));
        var dump = Path.Combine(Path.GetTempPath(), $"hc360-pt-{_suffix}.dump");
        using var saving = new CancellationTokenSource();
        var inserts = SaveAllTheTimeAsync(As(hospital, App), saving.Token);
        try
        {
            var counted = await tools.DumpAsync(dump, lowPriority: true, Ct);
            await saving.CancelAsync();
            await inserts;

            counted.Keys.ShouldBe(["patients.patients", "billing.bills", "audit.audit_events"], ignoreOrder: true, "the key tables this database has");
            var database = await tools.CreateAsync(64L << 20, Ct);
            try
            {
                await tools.RestoreAsync(database, dump, Ct);

                (await tools.CountRowsAsync(database, [.. counted.Keys], Ct)).ShouldBe(counted, "the dump holds the very rows counted");
                (await CountAsync(As(hospital, App), "patients.patients")).ShouldBeGreaterThan(counted["patients.patients"], "patients were saved while the dump ran");
                (await CountAsync(As(On(server, database), Restorer), "platform.server_nodes")).ShouldBe(0, "no server's heartbeat is backed up");
            }
            finally
            {
                await tools.DropAsync(database, CancellationToken.None);
            }

            (await DatabaseExistsAsync(server, database)).ShouldBeFalse();
            (await DatabaseExistsAsync(server, Database)).ShouldBeTrue("the hospital's database is never touched");
        }
        finally
        {
            await saving.CancelAsync();
            File.Delete(dump);
        }
    }

    /// <summary>
    /// The whole chain with the real tools: the server's own backup of the database (pg_dump in its counted snapshot,
    /// encrypted with the recovery key, read back and listed by pg_restore) passes its test restore, which opens it as a
    /// restore does and restores it into a scratch database, as the test-restore account.
    /// </summary>
    [Fact]
    public async Task A_backup_the_server_made_passes_its_test_restore()
    {
        var server = Server();
        var root = Path.Combine(Path.GetTempPath(), "hc360-tests", "pt-" + _suffix);
        var options = new PlatformOptions { DataDirectory = root };
        options.Backup.TestRestore.CheckRoom = await DataDirectoryIsHereAsync(server);
        var tools = Tools(As(On(server, Database), App), As(On(server, "postgres"), Restorer), options);
        var directories = new DataDirectories(options);
        directories.EnsureCreated();
        try
        {
            var protection = new EphemeralDataProtectionProvider();
            var protector = new FieldProtector(directories, protection);
            var recoveryKeys = new RecoveryKeyStore(directories, protection, protector, TimeProvider.System);
            var made = await new BackupService(Substitute.For<IDbContextFactory<HospitalDbContext>>(), Options.Create(options), directories, recoveryKeys, protector,
                    new Auditing.AuditSealKey(directories, protection), new NoDocumentsLock(), tools, Substitute.For<INotificationService>(), TimeProvider.System,
                    NullLogger<BackupService>.Instance)
                .CreateAsync(BackupKind.Manual, DateTimeOffset.UtcNow, includeDocuments: true, [], Ct);
            made.Warning.ShouldBeNull("pg_restore lists the dump as the backup is made");
            var run = new BackupRun
            {
                StartedAt = made.StartedAt,
                Kind = made.Kind,
                Status = BackupStatus.Succeeded,
                FileName = made.FileName,
                Sha256 = made.Sha256,
                VerifiedAt = made.VerifiedAt,
                FormatVersion = BackupEncryption.KeyedVersion,
                RecoveryKeyId = made.RecoveryKeyId,
            };

            var outcome = await new BackupRestoreTest(Substitute.For<IDbContextFactory<HospitalDbContext>>(), Options.Create(options), directories, recoveryKeys, tools,
                    tools, Substitute.For<INotificationService>(), TimeProvider.System, NullLogger<BackupRestoreTest>.Instance)
                .TestAsync(run, _ => Task.CompletedTask, Ct);

            outcome.Passed.ShouldBeTrue(outcome.Note);
            outcome.Note.ShouldContain("its 3 key tables hold the 3,000 rows recorded when the backup was made");
            Directory.EnumerateFiles(directories.Temp).ShouldBeEmpty("no plain database dump is left behind");
        }
        finally
        {
            Directory.Delete(root, recursive: true);
        }
    }

    /// <summary>A scratch database left by a test that was cut off (a power cut, a restart) is dropped before the next is made.</summary>
    [Fact]
    public async Task A_scratch_database_left_by_an_earlier_test_is_dropped_first()
    {
        var server = Server();
        var restorer = As(On(server, "postgres"), Restorer);
        var leftover = PostgresTools.ScratchPrefix + "0123456789ab";
        await ExecuteAsync(restorer, $"CREATE DATABASE {leftover}");
        var tools = Tools(As(On(server, Database), App), restorer, checkRoom: false);

        var database = await tools.CreateAsync(1L << 20, Ct);
        await tools.DropAsync(database, CancellationToken.None);

        (await DatabaseExistsAsync(server, leftover)).ShouldBeFalse();
        await Should.ThrowAsync<ArgumentException>(() => tools.DropAsync(Database, CancellationToken.None), "only a scratch database is ever dropped");
    }

    /// <summary>
    /// Without an account that may create databases, the account the server works as is used, which may not: the test
    /// restore says so, and what to do, rather than PostgreSQL's "permission denied".
    /// </summary>
    [Fact]
    public async Task An_account_that_may_not_create_databases_is_told_apart_with_what_to_do()
    {
        var server = Server();
        var tools = Tools(As(On(server, Database), App), restore: null, checkRoom: false);

        var refused = await Should.ThrowAsync<ScratchDatabaseException>(() => tools.CreateAsync(1L << 20, Ct));

        refused.Message.ShouldStartWith($"The account test restores sign in as, {App}, may not create databases");
        refused.Message.ShouldContain("ConnectionStrings:BackupRestoreTest");
    }

    private string Server()
    {
        Assert.SkipUnless(!string.IsNullOrEmpty(_server), "Needs a PostgreSQL server the tests may create databases and accounts on (HC360_TEST_DATABASE).");
        return _server!;
    }

    private static PostgresTools Tools(string hospital, string? restore, bool checkRoom)
    {
        var options = new PlatformOptions();
        options.Backup.TestRestore.CheckRoom = checkRoom;
        return Tools(hospital, restore, options);
    }

    private static PostgresTools Tools(string hospital, string? restore, PlatformOptions options)
    {
        var settings = new Dictionary<string, string?> { ["ConnectionStrings:Hospital"] = hospital };
        if (restore is not null)
        {
            settings[$"ConnectionStrings:{BackupRestoreTest.ConnectionName}"] = restore;
        }

        return new PostgresTools(new ConfigurationBuilder().AddInMemoryCollection(settings).Build(), new DatabaseCredentials(hospital), Options.Create(options),
            NullLogger<PostgresTools>.Instance);
    }

    /// <summary>Whether the server's data directory is on this machine, where its free space can be read (not so in a container).</summary>
    private static async Task<bool> DataDirectoryIsHereAsync(string server)
    {
        await using var connection = new NpgsqlConnection(server);
        await connection.OpenAsync(Ct);
        await using var command = new NpgsqlCommand("SELECT setting FROM pg_settings WHERE name = 'data_directory'", connection);
        return await command.ExecuteScalarAsync(Ct) is string directory && Directory.Exists(directory);
    }

    private static async Task SaveAllTheTimeAsync(string connectionString, CancellationToken stop)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync(CancellationToken.None);
        while (!stop.IsCancellationRequested)
        {
            await using var insert = new NpgsqlCommand("INSERT INTO patients.patients (name) VALUES ('saved during the dump')", connection);
            await insert.ExecuteNonQueryAsync(CancellationToken.None);
            await Task.Delay(TimeSpan.FromMilliseconds(5), CancellationToken.None);
        }
    }

    private static async Task<long> CountAsync(string connectionString, string table)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync(Ct);
        await using var command = new NpgsqlCommand($"SELECT count(*) FROM {table}", connection);
        return (long)(await command.ExecuteScalarAsync(Ct))!;
    }

    private static async Task<bool> DatabaseExistsAsync(string server, string name)
    {
        await using var connection = new NpgsqlConnection(server);
        await connection.OpenAsync(Ct);
        await using var command = new NpgsqlCommand("SELECT count(*) FROM pg_database WHERE datname = @name", connection);
        command.Parameters.AddWithValue("name", name);
        return (long)(await command.ExecuteScalarAsync(Ct))! > 0;
    }

    private static async Task ExecuteAsync(string connectionString, string sql)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync(Ct);
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync(Ct);
    }

    private static string On(string server, string database) => new NpgsqlConnectionStringBuilder(server) { Database = database, Pooling = false }.ConnectionString;

    /// <summary>The connection string <paramref name="connectionString"/> signed in as <paramref name="role"/>, with the password it was given here.</summary>
    private string As(string connectionString, string role)
    {
        var builder = new NpgsqlConnectionStringBuilder(connectionString) { Username = role };
        builder.Password = role == Owner ? $"owner-{_suffix}" : role == App ? $"app-{_suffix}" : $"restore-{_suffix}";
        return builder.ConnectionString;
    }

    private sealed class NoDocumentsLock : IDocumentStoreLock
    {
        public Task<IAsyncDisposable> HoldSharedAsync(CancellationToken cancellationToken) => Task.FromResult<IAsyncDisposable>(new Released());

        private sealed class Released : IAsyncDisposable
        {
            public ValueTask DisposeAsync() => ValueTask.CompletedTask;
        }
    }

    /// <summary>deploy/windows/hc360-database-roles.sql, found above the test's folder.</summary>
    private static string RolesSql()
    {
        for (var folder = new DirectoryInfo(AppContext.BaseDirectory); folder is not null; folder = folder.Parent)
        {
            var path = Path.Combine(folder.FullName, "deploy", "windows", "hc360-database-roles.sql");
            if (File.Exists(path))
            {
                return path;
            }
        }

        throw new FileNotFoundException("deploy/windows/hc360-database-roles.sql was not found above the test's folder.");
    }
}
