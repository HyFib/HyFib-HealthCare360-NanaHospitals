using System.Text;
using ClosedXML.Excel;
using HyFib.HealthCare360.Modules.Analytics.Domain;
using HyFib.HealthCare360.Modules.Analytics.Features.Reports;
using HyFib.HealthCare360.Modules.Analytics.Reports;
using HyFib.HealthCare360.Modules.Analytics.Reports.Export;

namespace HyFib.HealthCare360.Modules.Analytics.Tests.Reports;

public sealed class ReportShapingAndExportTests
{
    private static readonly ReportColumn[] Columns =
    [
        new("department", "Department", ReportValueType.Text),
        new("visits", "Visits", ReportValueType.Integer),
        new("revenue", "Revenue", ReportValueType.Money),
        new("share", "Share %", ReportValueType.Percent),
    ];

    private static readonly List<object?[]> Rows =
    [
        ["Cardiology", 120, 55_000.50m, 30.1m],
        ["=cmd|' /C calc'!A0", 80, 12_000m, null],
        ["Orthopaedics", 200, 90_000m, 49.3m],
        [null, 5, 100m, 0.5m],
    ];

    [Fact]
    public void Sorting_is_type_aware_stable_and_puts_blanks_last()
    {
        ReportShaping.Sort(Rows, 1, descending: true).Select(r => r[1]).ShouldBe([200, 120, 80, 5]);
        ReportShaping.Sort(Rows, 0, descending: false).Select(r => r[0]).ShouldBe(["=cmd|' /C calc'!A0", "Cardiology", "Orthopaedics", null]);
        ReportShaping.Sort(Rows, 3, descending: true).Select(r => r[3]).ShouldBe([49.3m, 30.1m, 0.5m, null]);
        ReportShaping.SortOrder(Rows, -1, descending: false).ShouldBe([0, 1, 2, 3]);
        ReportShaping.Page(Rows, 2, 3).Count.ShouldBe(1);
    }

    [Fact]
    public void Charts_show_the_largest_categories_and_fold_the_rest_into_others()
    {
        var rows = Enumerable.Range(1, 20).Select(i => new object?[] { $"D{i}", i, (decimal)i, null }).ToList();
        var keys = Enumerable.Range(1, 20).Select(i => (string?)$"k{i}").ToList();

        var chart = ReportShaping.Chart(Columns, rows, new ReportChartHint(ReportChartType.Bar, "department", ["visits"], TopN: 5), rowKeys: keys)!;

        chart.Categories.ShouldBe(["D20", "D19", "D18", "D17", ReportShaping.OthersLabel]);
        chart.Series[0].Values.ShouldBe([20m, 19m, 18m, 17m, 136m]);
        chart.Keys.ShouldBe(["k20", "k19", "k18", "k17", null]);
        chart.CategoryType.ShouldBe(ReportValueType.Text);
    }

    [Fact]
    public void Percentages_are_never_summed_into_others_and_time_series_keep_their_order()
    {
        var rows = Enumerable.Range(1, 20).Select(i => new object?[] { $"D{i}", i, 0m, (decimal)i }).ToList();

        var percent = ReportShaping.Chart(Columns, rows, new ReportChartHint(ReportChartType.Bar, "department", ["share"], TopN: 5))!;
        var trend = ReportShaping.Chart(Columns, rows, new ReportChartHint(ReportChartType.Line, "department", ["visits"], TimeSeries: true, TopN: 5))!;

        percent.Categories.Count.ShouldBe(5);
        percent.Categories.ShouldNotContain(ReportShaping.OthersLabel);
        trend.Categories.Count.ShouldBe(20);
        trend.Categories[0].ShouldBe("D1");
        ReportShaping.Chart(Columns, rows, new ReportChartHint(ReportChartType.Table, "department", ["visits"])).ShouldBeNull();
        ReportShaping.Chart(Columns, rows, new ReportChartHint(ReportChartType.Pie, "department", ["visits", "revenue"]))!.Series.Count.ShouldBe(1);
    }

    [Fact]
    public void Csv_carries_the_header_footer_and_neutralises_formulas()
    {
        var file = ReportExporter.Export(Document(), ExportFormat.Csv);
        var text = Encoding.UTF8.GetString(file.Content);

        file.FileName.ShouldBe("revenue-by-department_20260901-20260915.csv");
        file.ContentType.ShouldBe("text/csv");
        file.Content.Take(3).ShouldBe(Encoding.UTF8.GetPreamble());
        text.ShouldContain("Nana Hospitals\r\n");
        text.ShouldContain("Revenue by department\r\n");
        text.ShouldContain("Period,01 Sep 2026 – 15 Sep 2026\r\n");
        text.ShouldContain("Generated by,\"Asha Rao (asha) on 15 Sep 2026, 12:00 PM IST\"");
        text.ShouldContain("'=cmd|' /C calc'!A0");
        text.ShouldContain("Cardiology,120,55000.50,30.1");
        text.ShouldContain("Total,405,157100.50,");
        text.TrimEnd().ShouldEndWith("Do not share outside the hospital.");
        text.ShouldContain(ReportExporter.Confidential);
    }

    [Theory]
    [InlineData("plain", "plain")]
    [InlineData("a,b", "\"a,b\"")]
    [InlineData("say \"hi\"", "\"say \"\"hi\"\"\"")]
    [InlineData("+91 98765", "'+91 98765")]
    [InlineData("@SUM(A1)", "'@SUM(A1)")]
    [InlineData("-12.50", "-12.50")]
    [InlineData("-cmd", "'-cmd")]
    public void Csv_fields_are_quoted_and_protected(string input, string expected) => ReportExporter.Escape(input).ShouldBe(expected);

    [Fact]
    public void Excel_export_has_the_header_table_totals_and_confidential_footer()
    {
        var file = ReportExporter.Export(Document(), ExportFormat.Xlsx);

        file.FileName.ShouldEndWith(".xlsx");
        using var workbook = new XLWorkbook(new MemoryStream(file.Content));
        var sheet = workbook.Worksheet(1);
        sheet.Name.ShouldBe("Revenue by department");
        sheet.Cell(1, 1).GetString().ShouldBe("Nana Hospitals");
        sheet.Cell(2, 1).GetString().ShouldBe("Revenue by department");

        var used = sheet.RangeUsed()!;
        var cells = used.CellsUsed().Select(c => c.GetString()).ToList();
        cells.ShouldContain("Generated by");
        cells.ShouldContain("Department");
        cells.ShouldContain("=cmd|' /C calc'!A0");
        cells.ShouldContain(c => c.StartsWith(ReportExporter.Confidential, StringComparison.Ordinal));
        used.CellsUsed().Any(c => c.HasFormula).ShouldBeFalse();

        // The printed page footer (Excel stores it as the odd-page footer of the sheet).
        using var package = new System.IO.Compression.ZipArchive(new MemoryStream(file.Content));
        using var sheetXml = new StreamReader(package.GetEntry("xl/worksheets/sheet1.xml")!.Open());
        var xml = sheetXml.ReadToEnd();
        var footer = System.Text.RegularExpressions.Regex.Match(xml, @"<(?:\w+:)?oddFooter>(.*?)</(?:\w+:)?oddFooter>");
        footer.Success.ShouldBeTrue();
        footer.Groups[1].Value.ShouldContain(ReportExporter.Confidential);

        var revenue = used.CellsUsed().First(c => c.DataType == XLDataType.Number && Math.Abs(c.GetDouble() - 55_000.5) < 0.001);
        revenue.Style.NumberFormat.Format.ShouldContain("₹");
    }

    private static ReportDocument Document() => new(
        "revenue-by-department",
        "20260901-20260915",
        "Nana Hospitals",
        "Revenue by department",
        "Revenue = net amount of finalized bill lines.",
        [new ReportFilterDto("Period", "01 Sep 2026 – 15 Sep 2026"), new ReportFilterDto("Facility", "Nana Hospitals — Main")],
        "Asha Rao (asha)",
        new DateTimeOffset(2026, 9, 15, 6, 30, 0, TimeSpan.Zero),
        "Live database",
        Columns,
        Rows,
        ["Total", 405, 157_100.50m, null],
        [new ReportFigure("net", "Net revenue", 157_100.50m, ReportValueType.Money)],
        ["A note."],
        ContainsPatientIdentifiers: false);
}
